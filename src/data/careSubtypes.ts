//
// '탈모 & 두피 케어' 카드는 기존 src/data/hairCareTypes.ts + hairCareClassifier.ts를
// 그대로 사용해요 (이미 서비스 중이라 건드리지 않았어요). 이 파일은 나머지 11개
// 케어카드의 세부 체질 분류 데이터를 담아요 — 홍채 진단 프로필, 문진 힌트, BMI/체형,
// 원인 메커니즘, 그리고 LUDIA 맞춤 솔루션(모임 루틴 · 식습관 · 운동 · 홈케어)까지.
//
// id 규칙: `${careCaseId}__${slug}` — 카드별로 고유해요.

export interface CareSubtype {
  id: string
  careCaseId: CareCaseId
  emoji: string
  label: string          // 유형 이름 (따옴표 안 제목)
  subtitle: string        // 괄호 안 부제
  color: string
  gradient: string
  glow: string
  bg: string
  border: string
  irisSign: string         // 홍채 진단 프로필
  symptomHints: string      // 문진 프로필
  bodyHint: string          // BMI / 체형 설명 (표시용 원문)
  bmiRange: [number, number] | null  // 점수 계산용 (없으면 체형과 무관)
  mechanism: string         // 원인 메커니즘
  routineClub: { name: string; activities: string[] }
  diet: { good: string[]; avoid: string[] }
  exercise: string[]
  homecare: string[]
  meetupCategory: MeetupCategory
  meetupNote: string
  /** '기관 징후 & 정기 모니터링' 카드에만 있는 병원 검진 안내 */
  monitoringGuide?: string
}

