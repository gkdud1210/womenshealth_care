function role(i: number) { return ROLE_COLORS[i % ROLE_COLORS.length] }

type SubtypeSeed = Omit<CareSubtype, 'color' | 'gradient' | 'glow' | 'bg' | 'border'>

function build(seeds: SubtypeSeed[]): Record<string, CareSubtype> {
  const out: Record<string, CareSubtype> = {}
  seeds.forEach((s, i) => { out[s.id] = { ...s, ...role(i) } })
  return out
}

